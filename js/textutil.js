// Работа с текстом: снятие диакритики, нормализация ответов, поиск.
// Модуль без DOM — используется и в браузере, и в Node-тестах.

/** Словацкие буквы с диакритикой (для панели ввода и проверок). */
export const SK_DIACRITICS = ['á', 'ä', 'č', 'ď', 'é', 'í', 'ĺ', 'ľ', 'ň', 'ó', 'ô', 'ŕ', 'š', 'ť', 'ú', 'ý', 'ž'];

/**
 * Убирает диакритику только у латинских букв: pätnásť → patnast.
 * Кириллицу не трогаем (иначе «й» превратилась бы в «и»).
 */
export function foldLatin(s) {
  return s.normalize('NFD').replace(/([A-Za-z])[̀-ͯ]+/g, '$1').normalize('NFC');
}

/** Есть ли в строке кириллица. */
export const hasCyrillic = (s) => /[Ѐ-ӿ]/.test(s || '');

/**
 * Нормализация для сравнения ответов:
 * регистр, лишние пробелы, ё→е, разные апострофы/тире, концевая пунктуация.
 */
export function normalizeAnswer(s) {
  return (s || '')
    .normalize('NFC')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[’`´ʼ]/g, "'")
    .replace(/[‐-―]/g, '-')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/^[\s.,!?;:…"«»„“]+|[\s.,!?;:…"«»„“]+$/g, '');
}

/** Ключ для поиска: без диакритики, регистра и ё. */
export function searchKey(s) {
  return foldLatin(normalizeAnswer(s));
}

/** Экранирование для регулярных выражений. */
export const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
